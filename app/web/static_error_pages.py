# nginx error codes that get a page (keys of STATIC_ERROR_PAGES as ints).
STATIC_ERROR_CODES: tuple[int, ...] = tuple(int(k) for k in STATIC_ERROR_PAGES)

UNKNOWN_HOST_PAGE = "unknown-host.html"
# Legacy name kept for configs still pointing at /50x.html.
LEGACY_GATEWAY_PAGE = "50x.html"


@lru_cache(maxsize=1)
def _jinja_env() -> Environment:
    # Standalone env: no request, no i18n globals, no branding lookup — the
    # output must be identical on every host (it is committed to the repo).
    return Environment(
        loader=FileSystemLoader(str(_TEMPLATES_DIR)),
        autoescape=select_autoescape(["html"]),
        keep_trailing_newline=True,
    )


def static_error_page(key: str | int) -> StaticErrorPage:
    return STATIC_ERROR_PAGES[str(key)]


def render_static_error_html(key: str | int) -> str:
    page = static_error_page(key)
    return _jinja_env().get_template(_TEMPLATE_NAME).render(
        page=page, icon_svg=_ICONS[page.icon]
    )


@cache
def static_error_html_bytes(key: str | int) -> bytes:
    """Cached UTF-8 page for app middlewares that answer before any route runs."""
    return render_static_error_html(key).encode("utf-8")


# Paths whose clients always expect machine-readable errors (compared lower-case).
_MACHINE_PREFIXES = ("/api/", "/internal/", "/microsoft-server-activesync", "/autodiscover/")


def wants_html_error(
    *,
    path: str,
    accept: str | None,
    sec_fetch_mode: str | None = None,
    sec_fetch_dest: str | None = None,
    x_requested_with: str | None = None,
) -> bool:
    """True for a browser navigation that should get a page instead of JSON.

    Mirrors ``app.main._wants_json_response``: HTML wins when the client accepts
    it, except on API / internal paths and for XHR / fetch().
    """
    if path.lower().startswith(_MACHINE_PREFIXES):
        return False
    if (x_requested_with or "").strip().lower() == "xmlhttprequest":
        return False
    mode = (sec_fetch_mode or "").strip().lower()
    if mode in ("cors", "same-origin", "no-cors", "websocket"):
        return False
    if mode == "navigate" or (sec_fetch_dest or "").strip().lower() in ("document", "iframe"):
        return True
    return "text/html" in (accept or "").lower()


def render_static_error_json(key: str | int) -> str:
    page = static_error_page(key)
    return json.dumps({"code": page.slug, "message": page.fr_message}, ensure_ascii=False) + "\n"


def render_static_error_text(key: str | int) -> str:
    return static_error_page(key).plain_text + "\n"


def build_static_error_files() -> dict[str, str]:
    """All files of the nginx error directory, keyed by file name."""
    from app.bastion.unknown_host_routes import render_unknown_host_page

    files: dict[str, str] = {}
    for key in STATIC_ERROR_PAGES:
        files[f"{key}.html"] = render_static_error_html(key)
        files[f"{key}.json"] = render_static_error_json(key)
        files[f"{key}.txt"] = render_static_error_text(key)
    files[UNKNOWN_HOST_PAGE] = render_unknown_host_page()
    files[LEGACY_GATEWAY_PAGE] = files["502.html"]
    return files


def write_static_error_files(directory: Path) -> list[Path]:
    """(Re)write the nginx error directory; drop files no longer generated."""
    directory.mkdir(parents=True, exist_ok=True)
    files = build_static_error_files()
    written: list[Path] = []
    for name, content in sorted(files.items()):
        path = directory / name
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        written.append(path)
    for stale in directory.iterdir():
        if stale.is_file() and stale.name not in files:
            stale.unlink()
    return written
