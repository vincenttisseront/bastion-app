"""Self-contained branded error pages served by bastion-nginx (and app middlewares).

nginx must be able to answer a 502 while bastion-app is down, so these pages are
plain files baked into the bastion-nginx image (``docker/nginx/errors/``,
regenerated by ``scripts/generate_nginx_error_pages.py``). Each page exists in
three variants that nginx picks per location:

- ``<key>.html``  — browser navigations (portal look, FR + EN, inline CSS/SVG,
  no external asset, no product or company name: unknown Hosts reach them too);
- ``<key>.json``  — portal ``/api/*`` (same ``{"code", "message"}`` shape as
  ``app.api_errors.api_error_response``);
- ``<key>.txt``   — ActiveSync / Autodiscover / M2M clients (never HTML).

``unknown-host.html`` mirrors the neutral 403 of ``/internal/unknown-host`` so
an unknown Host never sees portal styling, even when bastion-app is down.
"""

