    slug: str
    tone: str  # "err" | "warn"
    icon: str
    fr_title: str
    fr_message: str
    en_title: str
    en_message: str

    @property
    def plain_text(self) -> str:
        return f"{self.status} {self.fr_title} / {self.en_title}"


