"""Virtual-patch packs (pre-CRS) — toggle via WafProfile, suggest from traffic."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from sqlalchemy.orm import Session

from app.bastion.modsec_audit_aggregator import read_audit_summary
from app.models import WafProfile
from app.sso_settings import Settings

PACK_PHP2SHELL = "php2shell"
PACK_IDS = frozenset({PACK_PHP2SHELL})

# Rule ids shipped in docker/nginx/modsecurity/bastion-virtual-patches.conf
PHP2SHELL_RULE_IDS = frozenset(
    {"100096180", "100096181", "100096182", "100096183", "100096184"}
)

VIRTUAL_PATCHES_ENABLED_FILENAME = "bastion-virtual-patches-enabled.conf"
VIRTUAL_PATCHES_SOURCE = "/etc/nginx/modsecurity/bastion-virtual-patches.conf"


def profile_pack_enabled(profile: WafProfile, pack_id: str) -> bool:
    if pack_id == PACK_PHP2SHELL:
        return bool(getattr(profile, "patch_php2shell_enabled", True))
    return False


def render_virtual_patches_enabled_conf(*, php2shell_enabled: bool) -> str:
    """Overlay included by main-*.conf — Include source file or empty stub."""
    lines = [
        "# Generated by nginx_waf_export — do not edit",
        "# Included from main-*.conf instead of a hard Include of bastion-virtual-patches.conf.",
    ]
    if php2shell_enabled:
        lines.append(
            f"# Pack {PACK_PHP2SHELL} enabled (CVE-2026-109618 / CVE-2026-109619)."
        )
        lines.append(f"Include {VIRTUAL_PATCHES_SOURCE}")
    else:
        lines.append(f"# Pack {PACK_PHP2SHELL} disabled (WafProfile.patch_php2shell_enabled=false).")
    lines.append("")
    return "\n".join(lines)


def _audit_hints_php2shell(summary: dict[str, Any]) -> dict[str, Any]:
    """Heuristic: multipart / PHP CRS families or our virtual-patch rule ids in audit."""
    if not summary.get("present"):
        return {"signal": False, "reasons": []}
    reasons: list[str] = []
    windows = summary.get("windows") or {}
    data = windows.get("7d") or windows.get("24h") or {}
    families = data.get("families") or {}
    if int(families.get("php") or 0) > 0:
        reasons.append("famille CRS php active dans l'audit")
    if int(families.get("rce") or 0) > 0:
        reasons.append("famille CRS rce active dans l'audit")
    rules = data.get("top_rules") or summary.get("top_rules") or []
    for item in rules:
        if not isinstance(item, dict):
            continue
        rid = str(item.get("rule_id") or item.get("id") or "").strip()
        if rid in PHP2SHELL_RULE_IDS:
            reasons.append(f"règle virtual-patch {rid} déjà vue")
            break
        label = str(item.get("label") or item.get("message") or "").lower()
        if "multipart" in label or "php" in label:
            reasons.append("règles multipart/php dans le top audit")
            break
    recent = summary.get("recent_events") or []
    for ev in recent[:40]:
        if not isinstance(ev, dict):
            continue
        msg = str(ev.get("message") or "").lower()
        if "php2shell" in msg or "php_session_upload" in msg:
            reasons.append("événement audit tagué php2shell / upload_progress")
            break
    # Dedupe preserve order
    seen: set[str] = set()
    uniq = []
    for r in reasons:
        if r not in seen:
            seen.add(r)
            uniq.append(r)
    return {"signal": bool(uniq), "reasons": uniq}


def build_virtual_patches_panel(
    db: Session,
    settings: Settings,
    profile: WafProfile,
) -> dict[str, Any]:
    summary = read_audit_summary(settings)
    hints = _audit_hints_php2shell(summary)
    enabled = profile_pack_enabled(profile, PACK_PHP2SHELL)
    suggest_enable = (not enabled) and bool(hints.get("signal"))
    repo_file = (
        Path(__file__).resolve().parents[2]
        / "docker"
        / "nginx"
        / "modsecurity"
        / "bastion-virtual-patches.conf"
    )
    return {
        "packs": [
            {
                "id": PACK_PHP2SHELL,
                "name": "PHP2Shell",
                "cves": ["CVE-2026-109618", "CVE-2026-109619"],
                "enabled": enabled,
                "rule_ids": sorted(PHP2SHELL_RULE_IDS),
                "detail": (
                    "Virtual patches pre-CRS (POST PHPSESSID, upload_progress, "
                    "filenames PHP, multipart imbriqué / sans Content-Length)."
                ),
                "source_present": repo_file.is_file(),
                "suggest_enable": suggest_enable,
                "suggest_reasons": hints.get("reasons") or [],
            }
        ],
        "any_suggest_enable": suggest_enable,
    }
