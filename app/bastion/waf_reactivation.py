def render_modsecurity_switch(*, family: str, enabled: bool) -> str:
    state = "on" if enabled else "off"
    label = {
        "portal": "Portal",
        "subdomain": "Subdomain",
        "public": "Public proxy",
    }.get(family, family)
    return (
        "# Generated by waf_reactivation — do not edit\n"
        f"# {label} server-level ModSecurity connector ({state}).\n"
        f"modsecurity {state};\n"
    )


