"""Idea 10 — draft pytest / Playwright tests (developer use only).

Never exposed as a route and refused when ``PORTAL_ENVIRONMENT=production``.
The draft is written under ``tests/_llm_drafts/`` (git-ignored) for a human
to review, rename and move; it is never collected or run automatically.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from app import re_safe
from app.llm.client import get_llm_client
from app.sso_settings import Settings

DRAFTS_DIR = Path("tests") / "_llm_drafts"
_MAX_SOURCE = 18_000
_SAFE_NAME = re_safe.compile(r"[^a-z0-9_]+")

SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "framework": {"type": "string", "enum": ["pytest", "playwright"]},
        "summary": {"type": "string", "maxLength": 600},
        "code": {"type": "string", "maxLength": 20000},
        "notes": {"type": "array", "items": {"type": "string", "maxLength": 300}, "maxItems": 8},
    },
    "required": ["framework", "summary", "code", "notes"],
    "additionalProperties": False,
}

_PYTEST_HINTS = (
    "Conventions du dépôt : pytest avec asyncio_mode=auto ; fixtures `client` "
    "(TestClient FastAPI, en-têtes admin {'X-Email': 'admin@example.com', "
    "'X-Groups': 'portal-admins'}), `db_session` (SQLite en mémoire), `mock_http` "
    "(respx). Helper `from tests.conftest import csrf_token_for`. Pas d'accès "
    "réseau réel, pas de secrets réels."
)
_PLAYWRIGHT_HINTS = (
    "Conventions : @playwright/test en TypeScript, tests/e2e/*.spec.ts, baseURL via "
    "E2E_BASE_URL, helper `loginBreakGlass(page, user, pw)` de ./fixtures/auth ; "
    "le test doit faire test.skip() si E2E_BASE_URL n'est pas défini."
)


class DraftRefused(RuntimeError):
    pass


async def generate_test_draft(
    settings: Settings,
    source_path: Path,
    *,
    framework: str = "pytest",
    focus: str = "",
) -> tuple[Path, dict[str, Any]]:
    if str(getattr(settings, "environment", "")).lower() == "production":
        raise DraftRefused("génération de tests refusée en production")
    if not getattr(settings, "llm_enabled", False):
        raise DraftRefused("LLM_ENABLED=false")
    source = source_path.read_text(encoding="utf-8")[:_MAX_SOURCE]
    instructions = (
        f"Écris un fichier de tests {framework} pour le module fourni du portail "
        "Bastion : cas nominaux, cas limites et cas d'erreur, un test par "
        "comportement, noms explicites. Le code doit être complet et exécutable. "
        + (_PYTEST_HINTS if framework == "pytest" else _PLAYWRIGHT_HINTS)
        + (f" Priorité demandée : {focus[:300]}" if focus else "")
    )
    result = await get_llm_client(settings).generate_json(
        task="test_generation",
        instructions=instructions,
        data={"chemin": source_path.as_posix(), "source": source},
        schema=SCHEMA,
        think=True,
    )
    if result.outcome != "ok" or not result.value:
        raise DraftRefused(f"assistant indisponible ({result.outcome})")
    stem = _SAFE_NAME.sub("_", source_path.stem.lower()).strip("_") or "module"
    ext = ".py" if result.value["framework"] == "pytest" else ".spec.ts"
    DRAFTS_DIR.mkdir(parents=True, exist_ok=True)
    # "draft_*" never matches pytest's test_*.py / *_test.py collection patterns.
    out = DRAFTS_DIR / f"draft_{stem}{ext}"
    header = (
        f"# DRAFT generated by {result.model} — review before use (prompt {result.prompt_sha256[:12]})\n"
        if ext == ".py"
        else f"// DRAFT generated by {result.model} — review before use (prompt {result.prompt_sha256[:12]})\n"
    )
    out.write_text(header + result.value["code"].rstrip() + "\n", encoding="utf-8")
    return out, result.value
