#!/usr/bin/env bash
# Make /var/log/nginx/apps writable for nginx uid 101, or redirect access_log to tmpfs.
# Shared by entrypoint + watch-exports-reload (sync rewrites conf with apps/ paths).
set -euo pipefail

APPS="${NGINX_APPS_LOG_DIR:-/var/log/nginx/apps}"
FALLBACK="${NGINX_APPS_LOG_FALLBACK:-/var/log/nginx/apps-fallback}"

_writable_by_nginx() {
  local dir="$1"
  [[ -d "$dir" ]] || return 1
  if command -v su-exec >/dev/null 2>&1; then
    su-exec nginx:nginx touch "$dir/.bastion-write-probe" 2>/dev/null || return 1
    rm -f "$dir/.bastion-write-probe" 2>/dev/null || true
    return 0
  fi
  touch "$dir/.bastion-write-probe" 2>/dev/null || return 1
  rm -f "$dir/.bastion-write-probe" 2>/dev/null || true
  return 0
}

_precreate_access_logs() {
  grep -RhoE 'access_log[[:space:]]+/var/log/nginx/apps/[^;[:space:]]+' \
    /etc/nginx/conf.d /etc/nginx/includes 2>/dev/null \
    | awk '{print $2}' | sort -u \
    | while IFS= read -r logf; do
        [[ -n "$logf" ]] || continue
        touch "$logf" 2>/dev/null || true
      done
}

_redirect_to_tmpfs() {
  echo "WARN: ${APPS} not writable by uid 101 — redirecting apps logs to ${FALLBACK} (tmpfs)" >&2
  echo "WARN: fix host: chown -R 101:65532 …/nginx-logs && chmod -R ug+rwX …/nginx-logs" >&2
  mkdir -p "$FALLBACK" 2>/dev/null || true
  chown -R nginx:nginx "$FALLBACK" 2>/dev/null || true
  chmod 770 "$FALLBACK" 2>/dev/null || true
  find /etc/nginx/conf.d /etc/nginx/includes /etc/nginx/snippets \
    -type f \( -name '*.conf' -o -name '*.map' \) 2>/dev/null \
    | while IFS= read -r f; do
        sed -i "s|/var/log/nginx/apps/|${FALLBACK}/|g" "$f" 2>/dev/null || true
      done
  mkdir -p /etc/nginx/modsecurity/generated 2>/dev/null || true
  cat > /etc/nginx/modsecurity/generated/audit-log-path.conf <<EOF
# Generated by fix-nginx-logs.sh — apps volume not writable by uid 101
SecAuditLog ${FALLBACK}/modsec_audit.log
EOF
}

_write_audit_log_default() {
  mkdir -p /etc/nginx/modsecurity/generated 2>/dev/null || true
  cat > /etc/nginx/modsecurity/generated/audit-log-path.conf <<EOF
# Generated by fix-nginx-logs.sh — nginx-logs volume OK
SecAuditLog ${APPS}/modsec_audit.log
EOF
}

mkdir -p "$APPS" 2>/dev/null || true

if [[ "$(id -u)" -eq 0 ]]; then
  _precreate_access_logs
  chown -R 101:65532 "$APPS" 2>/dev/null || true
  # Owner+group only (nginx 101 / app 65532) — no world-writable (shell:S2612).
  chmod -R ug+rwX "$APPS" 2>/dev/null || true
  find "$APPS" -type d -exec chmod 2770 {} \; 2>/dev/null || true
  find "$APPS" -type f -exec chmod 660 {} \; 2>/dev/null || true
fi

if _writable_by_nginx "$APPS"; then
  _write_audit_log_default
  exit 0
fi

_redirect_to_tmpfs
if ! _writable_by_nginx "$FALLBACK"; then
  echo "ERROR: neither ${APPS} nor ${FALLBACK} writable by nginx — cannot start/reload" >&2
  exit 1
fi
exit 0
