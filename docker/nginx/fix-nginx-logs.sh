#!/usr/bin/env bash
# Point nginx access/error logs away from sticky host volume files when needed.
# Shared by entrypoint + watch-exports-reload.
set -euo pipefail

APPS="${NGINX_APPS_LOG_DIR:-/var/log/nginx/apps}"
FALLBACK="${NGINX_APPS_LOG_FALLBACK:-/var/log/nginx/apps-fallback}"
# Default: always use tmpfs for conf log paths so :8080 binds even when
# portal.access.log is root-owned and CAP_CHOWN/FOWNER are missing.
# Set BASTION_NGINX_FORCE_LOG_TMPFS=0 to keep /var/log/nginx/apps when writable.
FORCE_TMPFS="${BASTION_NGINX_FORCE_LOG_TMPFS:-1}"

_nginx_can_append() {
  local f="$1"
  if command -v su-exec >/dev/null 2>&1; then
    su-exec nginx:nginx sh -c ": >> \"$f\"" 2>/dev/null
  else
    sh -c ": >> \"$f\"" 2>/dev/null
  fi
}

_writable_by_nginx() {
  local dir="$1"
  [[ -d "$dir" ]] || return 1
  if command -v su-exec >/dev/null 2>&1; then
    su-exec nginx:nginx touch "$dir/.bastion-write-probe" 2>/dev/null || return 1
    rm -f "$dir/.bastion-write-probe" 2>/dev/null || true
    return 0
  fi
  touch "$dir/.bastion-write-probe" 2>/dev/null || return 1
  rm -f "$dir/.bastion-write-probe" 2>/dev/null || true
  return 0
}

_list_apps_log_paths() {
  grep -RhoE '(access_log|error_log)[[:space:]]+/var/log/nginx/apps/[^;[:space:]]+' \
    /etc/nginx/conf.d /etc/nginx/includes 2>/dev/null \
    | awk '{print $2}' | sort -u
}

_ensure_log_files_writable() {
  local logf fail=0
  while IFS= read -r logf; do
    [[ -n "$logf" ]] || continue
    if _nginx_can_append "$logf"; then
      continue
    fi
    rm -f "$logf" 2>/dev/null || true
    if command -v su-exec >/dev/null 2>&1; then
      su-exec nginx:nginx touch "$logf" 2>/dev/null || true
    else
      touch "$logf" 2>/dev/null || true
    fi
    if [[ "$(id -u)" -eq 0 ]]; then
      chown 101:65532 "$logf" 2>/dev/null || true
      chmod 660 "$logf" 2>/dev/null || true
    fi
    if ! _nginx_can_append "$logf"; then
      echo "WARN: cannot make ${logf} writable for uid 101" >&2
      fail=$((fail + 1))
    fi
  done < <(_list_apps_log_paths)
  # Also probe the usual portal TLS log even if grep missed it (partial conf).
  if [[ -e "${APPS}/portal.access.log" ]] && ! _nginx_can_append "${APPS}/portal.access.log"; then
    fail=$((fail + 1))
  fi
  [[ "$fail" -eq 0 ]]
}

_redirect_to_tmpfs() {
  echo "INFO: nginx apps logs → ${FALLBACK} (tmpfs) — Accès apps TLS logs empty until volume is 101:65532" >&2
  mkdir -p "$FALLBACK" 2>/dev/null || true
  chown -R nginx:nginx "$FALLBACK" 2>/dev/null || true
  chmod 770 "$FALLBACK" 2>/dev/null || true
  find /etc/nginx/conf.d /etc/nginx/includes /etc/nginx/snippets \
    -type f \( -name '*.conf' -o -name '*.map' \) 2>/dev/null \
    | while IFS= read -r f; do
        sed -i "s|/var/log/nginx/apps/|${FALLBACK}/|g" "$f" 2>/dev/null || true
      done
  mkdir -p /etc/nginx/modsecurity/generated 2>/dev/null || true
  cat > /etc/nginx/modsecurity/generated/audit-log-path.conf <<EOF
# Generated by fix-nginx-logs.sh — tmpfs fallback (volume may be sticky)
SecAuditLog ${FALLBACK}/modsec_audit.log
EOF
}

_write_audit_log_default() {
  mkdir -p /etc/nginx/modsecurity/generated 2>/dev/null || true
  cat > /etc/nginx/modsecurity/generated/audit-log-path.conf <<EOF
# Generated by fix-nginx-logs.sh — nginx-logs volume OK
SecAuditLog ${APPS}/modsec_audit.log
EOF
}

mkdir -p "$APPS" 2>/dev/null || true

if [[ "$(id -u)" -eq 0 ]]; then
  while IFS= read -r logf; do
    [[ -n "$logf" ]] || continue
    touch "$logf" 2>/dev/null || true
  done < <(_list_apps_log_paths)
  chown -R 101:65532 "$APPS" 2>/dev/null || true
  chmod -R ug+rwX "$APPS" 2>/dev/null || true
  find "$APPS" -type d -exec chmod 2770 {} \; 2>/dev/null || true
  find "$APPS" -type f -exec chmod 660 {} \; 2>/dev/null || true
fi

if [[ "$FORCE_TMPFS" == "1" ]]; then
  _redirect_to_tmpfs
elif _writable_by_nginx "$APPS" && _ensure_log_files_writable; then
  _write_audit_log_default
  exit 0
else
  _redirect_to_tmpfs
fi

if ! _writable_by_nginx "$FALLBACK"; then
  echo "ERROR: ${FALLBACK} not writable by nginx — cannot start/reload" >&2
  exit 1
fi
exit 0
